/*
  Generates SQL from the TypeScript sources of truth, so the database and the
  shared package cannot drift apart:

    node shared/scripts/to-sql.ts catalog   # upserts for services + service_offers
    node shared/scripts/to-sql.ts demo      # private.demo_subscription_defs()

  The output was used to write the catalog and demo-data migrations. Applied
  migrations must never be edited: after changing catalog.ts or seed.ts, run
  `supabase migration new <name>` and paste the new output into that file
  (the statements are idempotent upserts / create-or-replace).

  Runs on Node >= 23.6 (built-in TypeScript type stripping).
*/
import { CATALOG, POPULAR_IDS, type PlanOffer } from '../src/catalog.ts'
import { DEMO_DEFS } from '../src/seed.ts'

const lit = (v: string | undefined | null) => (v == null ? 'null' : `'${v.replaceAll("'", "''")}'`)
const num = (v: number) => String(v)

function catalogSql(): string {
  const services = CATALOG.map((s) => {
    const rank = POPULAR_IDS.indexOf(s.id)
    return `  (${lit(s.id)}, ${lit(s.name)}, ${lit(s.category)}, ${lit(s.color)}, ${lit(s.overlap)}, ${rank >= 0 ? rank + 1 : 'null'})`
  })

  const offerRow = (id: string, kind: string, o: PlanOffer) =>
    `  (${lit(id)}, ${lit(kind)}, ${lit(o.plan)}, ${num(o.price)}, ${lit(o.currency)}, ${lit(o.cycle)})`
  const offers: string[] = []
  for (const s of CATALOG) {
    offers.push(offerRow(s.id, 'default', s.defaults))
    if (s.student) offers.push(offerRow(s.id, 'student', s.student))
    if (s.cheaper) offers.push(offerRow(s.id, 'cheaper', s.cheaper))
    if (s.annual) {
      offers.push(
        `  (${lit(s.id)}, 'annual', null, ${num(s.annual.price)}, ${lit(s.annual.currency)}, 'yearly')`,
      )
    }
  }

  return `-- Generated by \`node shared/scripts/to-sql.ts catalog\` from shared/src/catalog.ts.
-- Prices are illustrative sample values, not live provider prices.

insert into public.services (id, name, category, color, overlap, popular_rank)
values
${services.join(',\n')}
on conflict (id) do update set
  name = excluded.name,
  category = excluded.category,
  color = excluded.color,
  overlap = excluded.overlap,
  popular_rank = excluded.popular_rank;

insert into public.service_offers (service_id, kind, plan, price, currency, cycle)
values
${offers.join(',\n')}
on conflict (service_id, kind) do update set
  plan = excluded.plan,
  price = excluded.price,
  currency = excluded.currency,
  cycle = excluded.cycle;
`
}

function demoSql(): string {
  const json = `[\n${DEMO_DEFS.map((d) => `  ${JSON.stringify(d)}`).join(',\n')}\n]`
  return `-- Generated by \`node shared/scripts/to-sql.ts demo\` from DEMO_DEFS in shared/src/seed.ts.
-- Names, prices and cards are fictional sample values.
create or replace function private.demo_subscription_defs()
returns jsonb
language sql
immutable
set search_path = ''
as $defs$
  select $json$
${json}
$json$::jsonb
$defs$;
`
}

const mode = process.argv[2]
if (mode === 'catalog') process.stdout.write(catalogSql())
else if (mode === 'demo') process.stdout.write(demoSql())
else {
  process.stderr.write('usage: node shared/scripts/to-sql.ts <catalog|demo>\n')
  process.exit(1)
}
